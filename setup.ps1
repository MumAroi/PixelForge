#Requires -Version 5.1
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# Run from any directory; Cargo's generated paths are relative to the repo root.
Set-Location -LiteralPath $PSScriptRoot
if ([Environment]::OSVersion.Platform -ne 'Win32NT' -or -not [Environment]::Is64BitOperatingSystem) {
    throw 'This setup supports Windows x64 only.'
}
if (-not (Get-Command rustup -ErrorAction SilentlyContinue)) {
    throw 'Install Rust with rustup from https://rustup.rs, then open a new terminal.'
}
$vswhere = "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe"
if (-not (Test-Path -LiteralPath $vswhere)) {
    throw 'Install Visual Studio Build Tools with Desktop development with C++ (including a Windows SDK).'
}
$visualStudio = & $vswhere -latest -products '*' -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $visualStudio) {
    throw 'Install the Desktop development with C++ workload and a Windows SDK using Visual Studio Installer.'
}

$configPath = Join-Path $PSScriptRoot '.cargo/config.toml'
$marker = '# Generated by PixelForge setup.ps1'
if ((Test-Path -LiteralPath $configPath) -and -not (Get-Content -LiteralPath $configPath -Raw).StartsWith($marker)) {
    throw '.cargo/config.toml already exists and is not managed by setup.ps1. Preserve it and merge the tool settings manually.'
}

function Install-ToolArchive {
    param([string]$Name, [string]$Url, [string]$Sha256, [string]$ExpectedFile)
    $archive = Join-Path $PSScriptRoot ".tools/$Name.zip"
    $destination = Join-Path $PSScriptRoot ".tools/$Name"
    if (-not (Test-Path -LiteralPath $archive)) {
        Write-Host "Downloading $Name..."
        # A partial download is never reused on the next run.
        Invoke-WebRequest -UseBasicParsing -Uri $Url -OutFile "$archive.partial"
        Move-Item -LiteralPath "$archive.partial" -Destination $archive -Force
    }
    if ((Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant() -ne $Sha256) {
        throw "Checksum mismatch: $archive. Remove that archive and run setup again."
    }
    if (-not (Test-Path -LiteralPath (Join-Path $destination $ExpectedFile))) {
        Write-Host "Extracting $Name..."
        Expand-Archive -LiteralPath $archive -DestinationPath $destination -Force
    }
    if (-not (Test-Path -LiteralPath (Join-Path $destination $ExpectedFile))) {
        throw "Missing expected tool file: $Name/$ExpectedFile"
    }
}

New-Item -ItemType Directory -Force -Path '.tools' | Out-Null
Install-ToolArchive -Name 'libclang' `
    -Url 'https://files.pythonhosted.org/packages/0b/2d/3f480b1e1d31eb3d6de5e3ef641954e5c67430d5ac93b7fa7e07589576c7/libclang-18.1.1-py2.py3-none-win_amd64.whl' `
    -Sha256 '4dd2d3b82fab35e2bf9ca717d7b63ac990a3519c7e312f19fa8e86dcc712f7fb' `
    -ExpectedFile 'libclang-18.1.1.data/platlib/clang/native/libclang.dll'
Install-ToolArchive -Name 'cmake' `
    -Url 'https://files.pythonhosted.org/packages/18/58/909d6d99acb4e0886d0f660cf4e0fb26f586590e370b2e4ce7a10d06b145/cmake-3.31.6-py3-none-win_amd64.whl' `
    -Sha256 'bbaed969cef3c427f4f17591feb28db4ae595e3a4bbd45cb35522cee14df6a32' `
    -ExpectedFile 'cmake/data/bin/cmake.exe'

New-Item -ItemType Directory -Force -Path '.cargo' | Out-Null
@'
# Generated by PixelForge setup.ps1
[build]
jobs = 1

[target.x86_64-pc-windows-msvc]
linker = "rust-lld.exe"

[env]
CMAKE = { value = ".tools/cmake/cmake/data/bin/cmake.exe", relative = true, force = true }
LIBCLANG_PATH = { value = ".tools/libclang/libclang-18.1.1.data/platlib/clang/native", relative = true, force = true }
'@ | Set-Content -LiteralPath $configPath -Encoding ASCII

Write-Host 'Installing the Rust toolchain pinned in rust-toolchain.toml...'
& rustup show active-toolchain
if ($LASTEXITCODE -ne 0) { throw 'Rust toolchain setup failed.' }
Write-Host 'Downloading the dependencies recorded in Cargo.lock...'
& cargo fetch --locked --config net.offline=false
if ($LASTEXITCODE -ne 0) { throw 'Cargo dependency download failed.' }
Write-Host 'Setup complete. Run: cargo build --locked, then cargo run --locked'
